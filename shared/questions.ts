export function toPublicQuestion(q: MathQuestion): PublicMathQuestion {
  return {
    id: q.id,
    difficulty: q.difficulty,
    topic: q.topic,
    formulaHint: q.formulaHint,
    prompt: q.prompt,
    ...(q.imageDataUrl ? { imageDataUrl: q.imageDataUrl } : {}),
    choices: q.choices,
  }
}

/**
 * Returns a non-spoiler step-by-step setup clue for the "แนวคิดเริ่มต้น" Math Helper.
 */
export function getQuestionStepHint(q: MathQuestion): string {
  if (q.stepHint) return q.stepHint
  return `หัวข้อ "${q.topic}" — เริ่มจากตั้งสูตรหลัก: ${q.formulaHint} แล้วแยกกรณีหรือแทนค่าตัวเลขจากโจทย์ทีละขั้น`
}

/**
 * Picks an unanswered question for a player so they can NEVER farm points
 * by repeating the same question. Respects preferredDifficulty when available.
 */
export function pickNextQuestion(
  usedIds: ReadonlySet<string>,
  preferredDifficulty?: Difficulty,
  rng: () => number = Math.random,
  bank: readonly MathQuestion[] = QUESTION_BANK,
): MathQuestion | null {
  let candidates = bank.filter((q) => !usedIds.has(q.id))
  if (candidates.length === 0) {
    return null
  }
  if (preferredDifficulty) {
    const filtered = candidates.filter((q) => q.difficulty === preferredDifficulty)
    if (filtered.length > 0) {
      candidates = filtered
    }
  }
  const idx = Math.floor(rng() * candidates.length)
  return candidates[idx]
}
